    private static Compilation RunGenerator(
        Compilation compilation,
        CSharpParseOptions? parseOptions = null,
        Dictionary<string, string>? buildProperties = null)
    {
        GeneratorDriver driver = CSharpGeneratorDriver.Create(
            generators: [new DatabaseSetupGenerator().AsSourceGenerator()],
            parseOptions: parseOptions ?? _parseOptions,
            optionsProvider: buildProperties is null
                ? null
                : new MockAnalyzerConfigOptionsProvider(buildProperties));

        driver.RunGeneratorsAndUpdateCompilation(
            compilation, out var output, out _, TestContext.Current.CancellationToken);

        Assert.Contains(
            output.SyntaxTrees,
            tree => tree.FilePath.EndsWith(".g.cs", StringComparison.Ordinal));

