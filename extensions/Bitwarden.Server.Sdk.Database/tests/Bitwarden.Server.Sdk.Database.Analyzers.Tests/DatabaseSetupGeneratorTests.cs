    private static Assembly EmitAndLoad(
        Compilation compilation,
        params (string ResourceName, string Content)[] embeddedScripts)
    {
        // The generated code and the schema it was generated from compile together, exactly as
        // they would in the consuming project.
        using var peStream = new MemoryStream();
        var result = compilation.Emit(
            peStream,
            manifestResources: embeddedScripts.Select(script => new ResourceDescription(
                script.ResourceName,
                () => new MemoryStream(Encoding.UTF8.GetBytes(script.Content)),
                isPublic: true)),
            cancellationToken: TestContext.Current.CancellationToken);

        Assert.True(
            result.Success,
            "Generated code failed to emit: "
            + string.Join(" | ", result.Diagnostics.Where(d => d.Severity == DiagnosticSeverity.Error)));

        return Assembly.Load(peStream.ToArray());
    }

