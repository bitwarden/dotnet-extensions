    private static readonly CSharpParseOptions _parseOptions = new(LanguageVersion.CSharp13);

    private static async Task<Compilation> BuildCompilationAsync(
        [StringSyntax("C#")] string source,
        IReadOnlyCollection<string>? excludeAssemblyNames = null,
        CSharpParseOptions? parseOptions = null)
    {
        var projectName = $"DatabaseSetupGeneratorTestProject-{Guid.NewGuid()}";
        var compilationOptions = new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary)
            .WithNullableContextOptions(NullableContextOptions.Enable);

        var project = new AdhocWorkspace().CurrentSolution
            .AddProject(projectName, projectName, LanguageNames.CSharp)
            .WithCompilationOptions(compilationOptions)
            .WithParseOptions(parseOptions ?? _parseOptions);

        // Everything the test host itself can load: the shared frameworks plus every package in
        // the dependency graph. A narrower set compiles the test source fine but leaves the
        // generated code short of references it legitimately uses, so its compilation can't be
        // checked.
        var references = PlatformAssemblies
            .Distinct(StringComparer.OrdinalIgnoreCase)
            .Where(dll => excludeAssemblyNames is null ||
                          !excludeAssemblyNames.Contains(
                              Path.GetFileNameWithoutExtension(dll),
                              StringComparer.OrdinalIgnoreCase));

        foreach (var dll in references)
            project = project.AddMetadataReference(MetadataReference.CreateFromFile(dll));

        project = project
            .AddDocument("TestSource.cs", SourceText.From(source, Encoding.UTF8))
            .Project;

        var compilation = await project.GetCompilationAsync(TestContext.Current.CancellationToken);
        if (compilation is null)
            Assert.Fail("Could not compile test project");

        return compilation;
    }

    private static async Task RunAsync(
        [StringSyntax("C#")] string source,
        [StringSyntax("C#")] string generatedSource,
        IReadOnlyCollection<string>? excludeAssemblyNames = null,
        string? projectDir = null,
        string? scriptPrefix = null,
        string? previousScriptPrefix = null)
    {
        var actual = await GenerateAsync(
            source, excludeAssemblyNames, projectDir, scriptPrefix, previousScriptPrefix);

        new DefaultVerifier().EqualOrDiff(generatedSource, actual);
    }

    private static async Task<string> GenerateAsync(
        [StringSyntax("C#")] string source,
        IReadOnlyCollection<string>? excludeAssemblyNames = null,
        string? projectDir = null,
        string? scriptPrefix = null,
        string? previousScriptPrefix = null)
    {
        var initialCompilation = await BuildCompilationAsync(source, excludeAssemblyNames);

        var initialDiagnostics = initialCompilation.GetDiagnostics(TestContext.Current.CancellationToken);

        if (initialDiagnostics.Length > 0)
        {
            Debug.WriteLine("Initial diagnostics:");
            foreach (var diagnostic in initialDiagnostics)
            {
                Debug.WriteLine(diagnostic.ToString());
            }
        }

        AnalyzerConfigOptionsProvider? optionsProvider = null;
        if (projectDir is not null || scriptPrefix is not null || previousScriptPrefix is not null)
        {
            var buildProperties = new Dictionary<string, string>();

            if (projectDir is not null)
                buildProperties["build_property.MSBuildProjectDirectory"] = projectDir;

            if (scriptPrefix is not null)
                buildProperties["build_property.BitSqlServerScriptPrefix"] = scriptPrefix;

            if (previousScriptPrefix is not null)
                buildProperties["build_property.BitPreviousSqlServerScriptPrefix"] = previousScriptPrefix;

            optionsProvider = new MockAnalyzerConfigOptionsProvider(buildProperties);
        }

        var generator = new DatabaseSetupGenerator().AsSourceGenerator();
        GeneratorDriver driver = CSharpGeneratorDriver.Create(
            generators: [generator],
            driverOptions: new GeneratorDriverOptions(IncrementalGeneratorOutputKind.None, trackIncrementalGeneratorSteps: true),
            parseOptions: _parseOptions,
            optionsProvider: optionsProvider
        );

        driver = driver.RunGeneratorsAndUpdateCompilation(
            initialCompilation,
            out var outputCompilation,
            out var generatorDiagnostics,
            TestContext.Current.CancellationToken);

        if (generatorDiagnostics.Length > 0)
        {
            Assert.Fail(
                "Generator reported diagnostics: "
                + string.Join(" | ", generatorDiagnostics.Select(d => d.ToString())));
        }

        // The generated source has to compile. Comparing its text would otherwise pass happily on
        // output that no consumer could build.
        var errors = outputCompilation
            .GetDiagnostics(TestContext.Current.CancellationToken)
            .Where(d => d.Severity == DiagnosticSeverity.Error)
            .ToList();

        Assert.True(
            errors.Count == 0,
            "Generated code does not compile: " + string.Join(" | ", errors.Select(e => e.ToString())));

        var runResult = driver.GetRunResult();

        var singleResult = Assert.Single(runResult.Results);

        var singleGeneratedSource = Assert.Single(singleResult.GeneratedSources);

        return singleGeneratedSource.SourceText.ToString();
    }

    /// <summary>Returns the body of a generated <c>_{provider}Entries</c> array.</summary>
    private static string EntriesFor(string generated, string provider)
    {
        var start = generated.IndexOf($"_{provider}Entries =", StringComparison.Ordinal);
        Assert.True(start >= 0, $"No _{provider}Entries array in generated source.");

        var end = generated.IndexOf("];", start, StringComparison.Ordinal);
        Assert.True(end >= 0, $"Unterminated _{provider}Entries array.");

        return generated.Substring(start, end - start).TrimEnd();
    }

